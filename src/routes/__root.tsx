function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <HeadContent />
      </head>
      <body suppressHydrationWarning>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();

  // Honour "Remember me = off": clear the persisted session once the browser
  // was fully closed (sessionStorage gone) since login.
  useEffect(() => {
    const ephemeral = localStorage.getItem("mehar_ephemeral");
    if (ephemeral && !sessionStorage.getItem("mehar_alive")) {
      localStorage.removeItem("mehar_ephemeral");
      localStorage.removeItem("dvr_token");
      localStorage.removeItem("token");
    }
    sessionStorage.setItem("mehar_alive", "1");
  }, []);

  // Sync auth-state across tabs
  useEffect(() => {
    const handleStorage = (e: StorageEvent) => {
      if (e.key === "dvr_token" || e.key === "token") {
        router.invalidate();
        queryClient.invalidateQueries();
      }
    };
    window.addEventListener("storage", handleStorage);
    return () => window.removeEventListener("storage", handleStorage);
  }, [queryClient, router]);

  return (
    <QueryClientProvider client={queryClient}>
      <Outlet />
      <Toaster richColors position="top-center" />
    </QueryClientProvider>
  );
}
